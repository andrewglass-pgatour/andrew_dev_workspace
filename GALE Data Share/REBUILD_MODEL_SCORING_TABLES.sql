CREATE OR REPLACE PROCEDURE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.REBUILD_MODEL_SCORING_TABLES()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
BEGIN

  -- ---------------------------------------------------------------------------
  -- 1. Source Views -> Transient Tables (CTAS required for VIEWs)
  -- ---------------------------------------------------------------------------

  -- Amplitude
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TRANSIENT TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.AMPLITUDE_SUMMARY AS SELECT * FROM ANALYTICS.PROD_AMPLITUDE.MOPS_AMPLITUDE_SUMMARY';
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TRANSIENT TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.AMPLITUDE_CONTENT_ENGAGEMENT AS SELECT * FROM ANALYTICS.PROD_AMPLITUDE.GALE_AMPLITUDE_CONTENT_ENGAGEMENT_W_TIMESTAMP';

  -- Archtics
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TRANSIENT TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.ARCHTICS_TICKET_SUMMARY AS SELECT * FROM ANALYTICS.PROD_ARCHTICS.GALE_ARCHTICS_TICKET_SUMMARY_W_TIMESTAMP';
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TRANSIENT TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.ARCHTICS_TOURNAMENT_SUMMARY AS SELECT * FROM ANALYTICS.PROD_ARCHTICS.archtics_tournament_summary';

  -- Fanatics
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TRANSIENT TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.FANATICS_SUMMARY AS SELECT * FROM ANALYTICS.PROD_FANATICS.MOPS_FANATICS_SUMMARY';
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TRANSIENT TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.FANATICS_PURCHASE_DETAILS AS SELECT * FROM ANALYTICS.PROD_FANATICS.MOPS_FANATICS_PURCHASE_SUMMARY';

  -- Gigya
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TRANSIENT TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.GIGYA_SUMMARY AS SELECT * FROM ANALYTICS.PROD_GIGYA.MOPS_GIGYA_SUMMARY';

  -- EA Sports
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TRANSIENT TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.EA_SPORTS_SUMMARY AS SELECT * FROM ANALYTICS.PROD_EA.MOPS_EA_SPORTS_SUMMARY';

  -- Fantasy
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TRANSIENT TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.FANTASY_SUMMARY AS SELECT * FROM ANALYTICS.PROD_FANTASY.MOPS_FANTASY_SUMMARY';
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TRANSIENT TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.FANTASY_USER_LOG_DATA AS SELECT * FROM INTERMEDIATE.PROD_FANTASY.INT_FANTASY_USER_DAILY_LOG';

  -- Jebbit
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TRANSIENT TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.JEBBIT_SUMMARY AS SELECT * FROM ANALYTICS.PROD_JEBBIT.MOPS_JEBBIT_CAMPAIGN_SUMMARY';

  -- Safari
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TRANSIENT TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.SAFARI_SUMMARY AS SELECT * FROM ANALYTICS.PROD_SAFARI.MOPS_SAFARI_SUMMARY';

  -- ---------------------------------------------------------------------------
  -- 2. Permanent Base Tables -> Zero-Copy Clones (Instant metadata clone, 0 compute cost)
  -- ---------------------------------------------------------------------------

  -- TPC Sweeps & Vacations
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.TPC_SWEEPSTAKES_MEMBER CLONE PGAT.TOURNAMENT.TPC_SWEEPSTAKES_MEMBERS';
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.TPC_VACATIONS_ITINERARIES CLONE PGAT.TOURNAMENT.TPC_VACATIONS_ITINERARIES';
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.TPC_VACATIONS_ITINERARIES_DETAIL CLONE PGAT.TOURNAMENT.TPC_VACATIONS_ITINERARIES_DETAIL';
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.TPC_VACATIONS_RESERVATIONS CLONE PGAT.TOURNAMENT.TPC_VACATIONS_RESERVATIONS';

  -- Braze Currents Raw Permanent Base Tables
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.BRAZE_USERS_BEHAVIORS_SUBSCRIPTIONGROUP_STATECHANGE CLONE PGAT.BRAZE.USERS_BEHAVIORS_SUBSCRIPTIONGROUP_STATECHANGE';
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.BRAZE_USERS_BEHAVIORS_SUBSCRIPTIONGROUP_STATECHANGE__DEDUP CLONE PGAT.BRAZE.USERS_BEHAVIORS_SUBSCRIPTIONGROUP_STATECHANGE__DEDUP';
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.BRAZE_USERS_BEHAVIORS_SUBSCRIPTIONGROUP_STATECHANGE__DEDUP_CONFLICTTIME CLONE PGAT.BRAZE.USERS_BEHAVIORS_SUBSCRIPTIONGROUP_STATECHANGE__DEDUP_CONFLICTTIME';
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.BRAZE_USERS_BEHAVIORS_SUBSCRIPTIONGROUP_STATECHANGE__DEDUP_LATEST CLONE PGAT.BRAZE.USERS_BEHAVIORS_SUBSCRIPTIONGROUP_STATECHANGE__DEDUP_LATEST';
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.BRAZE_USERS_BEHAVIORS_SUBSCRIPTION_GLOBALSTATECHANGE CLONE PGAT.BRAZE.USERS_BEHAVIORS_SUBSCRIPTION_GLOBALSTATECHANGE';
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.BRAZE_USERS_CAMPAIGNS_CONVERSION CLONE PGAT.BRAZE.USERS_CAMPAIGNS_CONVERSION';
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.BRAZE_USERS_MESSAGES_CONTENTCARD_CLICK CLONE PGAT.BRAZE.USERS_MESSAGES_CONTENTCARD_CLICK';
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.BRAZE_USERS_MESSAGES_CONTENTCARD_IMPRESSION CLONE PGAT.BRAZE.USERS_MESSAGES_CONTENTCARD_IMPRESSION';
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.BRAZE_USERS_MESSAGES_CONTENTCARD_SEND CLONE PGAT.BRAZE.USERS_MESSAGES_CONTENTCARD_SEND';
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.BRAZE_USERS_MESSAGES_EMAIL_CLICKS CLONE PGAT.BRAZE.USERS_MESSAGES_EMAIL_CLICKS';
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.BRAZE_USERS_MESSAGES_EMAIL_OPEN CLONE PGAT.BRAZE.USERS_MESSAGES_EMAIL_OPEN';
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.BRAZE_USERS_MESSAGES_EMAIL_SENDS CLONE PGAT.BRAZE.USERS_MESSAGES_EMAIL_SENDS';
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.BRAZE_USERS_MESSAGES_EMAIL_UNSUBSCRIBE CLONE PGAT.BRAZE.USERS_MESSAGES_EMAIL_UNSUBSCRIBE';
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.BRAZE_USERS_MESSAGES_INAPPMESSAGE_ABORT CLONE PGAT.BRAZE.USERS_MESSAGES_INAPPMESSAGE_ABORT';
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.BRAZE_USERS_MESSAGES_INAPPMESSAGE_CLICK CLONE PGAT.BRAZE.USERS_MESSAGES_INAPPMESSAGE_CLICK';
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.BRAZE_USERS_MESSAGES_INAPPMESSAGE_IMPRESSION CLONE PGAT.BRAZE.USERS_MESSAGES_INAPPMESSAGE_IMPRESSION';
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.BRAZE_USERS_MESSAGES_PUSHNOTIFICATION_SEND CLONE PGAT.BRAZE.USERS_MESSAGES_PUSHNOTIFICATION_SEND';
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.BRAZE_USERS_MESSAGES_SMS_DELIVERY CLONE PGAT.BRAZE.USERS_MESSAGES_SMS_DELIVERY';
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.BRAZE_USERS_MESSAGES_SMS_INBOUNDRECEIVE CLONE PGAT.BRAZE.USERS_MESSAGES_SMS_INBOUNDRECEIVE';
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.BRAZE_USERS_MESSAGES_SMS_REJECTION CLONE PGAT.BRAZE.USERS_MESSAGES_SMS_REJECTION';
  EXECUTE IMMEDIATE 'CREATE OR REPLACE TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.BRAZE_USERS_MESSAGES_SMS_SEND CLONE PGAT.BRAZE.USERS_MESSAGES_SMS_SEND';

  -- ---------------------------------------------------------------------------
  -- 3. Filtered/Transformed Tables
  -- ---------------------------------------------------------------------------

  EXECUTE IMMEDIATE
    'CREATE OR REPLACE TRANSIENT TABLE GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING.SUBSCRIBER_EVENTS AS
     SELECT EMAILADDRESS, NEWSLETTER, lower(EVENTTYPE) AS EVENTTYPE, EVENTDATE, EVENTSOURCE  
     FROM PGAT.GOLDEN.SUBSCRIPTIONEVENTS
     WHERE EVENTDATE IS NOT NULL AND (lower(trim(EVENTTYPE)) != ''unknown'')';

  -- Re-grant Share Permissions
  EXECUTE IMMEDIATE 'GRANT SELECT ON ALL TABLES IN SCHEMA GALE_PGATOUR_MEMBERSHIP.MODEL_SCORING TO SHARE GALE_PGATOUR_MEMBERSHIP_SHARE';

  RETURN 'All MODEL_SCORING tables rebuilt successfully.';

END;
$$;
