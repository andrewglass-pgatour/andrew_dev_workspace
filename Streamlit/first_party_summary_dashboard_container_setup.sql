-- One-time setup for running first_party_summary_dashboard.py on Streamlit Container Runtime.
-- Replace the <PLACEHOLDERS>, run as a role that can create compute pools / integrations (e.g. ACCOUNTADMIN),
-- then deploy with:  snow streamlit deploy --replace   (from this folder)

-- Create dedicated database for Streamlit 
CREATE SCHEMA PGAT.STREAMLIT_APPS;

-- 1. Compute pool (small, auto-suspends when idle to limit cost)
CREATE COMPUTE POOL IF NOT EXISTS STREAMLIT_POOL
  MIN_NODES = 1
  MAX_NODES = 1
  INSTANCE_FAMILY = CPU_X64_XS
  AUTO_RESUME = TRUE
  AUTO_SUSPEND_SECS = 300;

-- 2. Network access so the container can install packages from PyPI
CREATE OR REPLACE NETWORK RULE PGAT.STREAMLIT_APPS.PYPI_NETWORK_RULE
  MODE = EGRESS
  TYPE = HOST_PORT
  VALUE_LIST = ('pypi.org', 'pypi.python.org', 'pythonhosted.org', 'files.pythonhosted.org');

CREATE OR REPLACE EXTERNAL ACCESS INTEGRATION PYPI_ACCESS_INTEGRATION
  ALLOWED_NETWORK_RULES = (PGAT.STREAMLIT_APPS.PYPI_NETWORK_RULE)
  ENABLED = TRUE;

-- 3. Create Streamlit_App_Owner role moving forward
CREATE ROLE IF NOT EXISTS STREAMLIT_APP_OWNER;
GRANT ROLE STREAMLIT_APP_OWNER TO ROLE SYSADMIN;          -- keep the role hierarchy tidy
GRANT ROLE STREAMLIT_APP_OWNER TO USER "AndrewGlass@pgatourhq.com";       -- so you can deploy

-- Where the app lives
GRANT USAGE ON DATABASE PGAT TO ROLE STREAMLIT_APP_OWNER;
GRANT USAGE, CREATE STREAMLIT, CREATE STAGE ON SCHEMA PGAT.STREAMLIT_APPS TO ROLE STREAMLIT_APP_OWNER;
GRANT USAGE ON NETWORK RULE PGAT.STREAMLIT_APPS.PYPI_NETWORK_RULE TO ROLE STREAMLIT_APP_OWNER;

-- Compute
GRANT USAGE, OPERATE ON COMPUTE POOL STREAMLIT_POOL TO ROLE STREAMLIT_APP_OWNER;
GRANT USAGE ON INTEGRATION PYPI_ACCESS_INTEGRATION TO ROLE STREAMLIT_APP_OWNER;
GRANT USAGE ON WAREHOUSE STREAMLIT_APP_WH_XSMALL TO ROLE STREAMLIT_APP_OWNER;

-- Data the dashboard reads (read-only)
GRANT USAGE ON DATABASE ANALYTICS TO ROLE STREAMLIT_APP_OWNER;
GRANT USAGE ON DATABASE INTERMEDIATE TO ROLE STREAMLIT_APP_OWNER;
GRANT USAGE ON DATABASE PGAT TO ROLE STREAMLIT_APP_OWNER;

GRANT USAGE ON ALL SCHEMAS IN DATABASE ANALYTICS TO ROLE STREAMLIT_APP_OWNER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE INTERMEDIATE TO ROLE STREAMLIT_APP_OWNER;

GRANT USAGE ON FUTURE SCHEMAS IN DATABASE ANALYTICS TO ROLE STREAMLIT_APP_OWNER;
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE INTERMEDIATE TO ROLE STREAMLIT_APP_OWNER;

GRANT SELECT ON ALL TABLES IN DATABASE ANALYTICS TO ROLE STREAMLIT_APP_OWNER;
GRANT SELECT ON ALL TABLES IN DATABASE INTERMEDIATE TO ROLE STREAMLIT_APP_OWNER;

GRANT SELECT ON ALL VIEWS IN DATABASE ANALYTICS TO ROLE STREAMLIT_APP_OWNER;
GRANT SELECT ON ALL VIEWS IN DATABASE INTERMEDIATE TO ROLE STREAMLIT_APP_OWNER;

GRANT SELECT ON FUTURE TABLES IN DATABASE ANALYTICS TO ROLE STREAMLIT_APP_OWNER;
GRANT SELECT ON FUTURE TABLES IN DATABASE INTERMEDIATE TO ROLE STREAMLIT_APP_OWNER;
GRANT SELECT ON FUTURE VIEWS IN DATABASE ANALYTICS TO ROLE STREAMLIT_APP_OWNER;
GRANT SELECT ON FUTURE VIEWS IN DATABASE INTERMEDIATE TO ROLE STREAMLIT_APP_OWNER;

-- PGAT: only what the dashboard actually reads
GRANT USAGE ON DATABASE PGAT TO ROLE STREAMLIT_APP_OWNER;
GRANT USAGE ON SCHEMA PGAT.GOLDEN TO ROLE STREAMLIT_APP_OWNER;
GRANT USAGE ON SCHEMA PGAT.LOOKUP TO ROLE STREAMLIT_APP_OWNER;
GRANT SELECT ON TABLE PGAT.GOLDEN.FAN TO ROLE STREAMLIT_APP_OWNER;
GRANT SELECT ON ALL TABLES IN SCHEMA PGAT.LOOKUP TO ROLE STREAMLIT_APP_OWNER;
